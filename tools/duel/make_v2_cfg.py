"""Build a local duel config: upstream chain.toml with [training] replaced by [v2.training].

The loader parses [v2.training] as a complete, standalone contract, so a wholesale
section swap reproduces the lane-A v2 training contract for duel.py / grid.py.
`corpus_mode` defaults to "stream_cpu" (the "shards" mode needs upstream's CPU VM).

    python make_v2_cfg.py UPSTREAM_CHAIN.toml OUT.toml [--set key=value ...]

--set values are written verbatim as TOML (quote strings: --set 'arch_preset="x"').
"""
from __future__ import annotations

import argparse
import re
import tomllib
from pathlib import Path

DEFAULT_SETS = {"corpus_mode": '"stream_cpu"'}
HEADER = re.compile(r"^\[([^\[\]]+)\]\s*(#.*)?$")


def section_spans(lines: list[str]) -> dict[str, tuple[int, int]]:
    """Map each [table] header to its (start, end) line span (header line included)."""
    heads = [(i, m.group(1).strip()) for i, l in enumerate(lines) if (m := HEADER.match(l.strip()))]
    ends = [i for i, _ in heads[1:]] + [len(lines)]
    return {name: (i, e) for (i, name), e in zip(heads, ends)}


def section_body(lines: list[str], span: tuple[int, int]) -> list[str]:
    return lines[span[0] + 1:span[1]]


def apply_sets(body: list[str], sets: dict[str, str]) -> list[str]:
    """Replace `key = ...` lines in place; append keys that are absent."""
    out, seen = [], set()
    for line in body:
        key = line.split("=", 1)[0].strip() if "=" in line and not line.lstrip().startswith("#") else None
        if key in sets:
            out.append(f"{key} = {sets[key]}\n")
            seen.add(key)
        else:
            out.append(line)
    while out and not out[-1].strip():
        out.pop()
    out += [f"{k} = {v}\n" for k, v in sets.items() if k not in seen]
    return out + ["\n"]


def build(upstream_text: str, sets: dict[str, str]) -> str:
    lines = upstream_text.splitlines(keepends=True)
    spans = section_spans(lines)
    start, end = spans["training"]
    body = apply_sets(section_body(lines, spans["v2.training"]), sets)
    head = ["# Generated by tools/duel/make_v2_cfg.py: [training] := upstream [v2.training].\n"]
    return "".join(head + lines[:start + 1] + body + lines[end:])


def parse_sets(items: list[str]) -> dict[str, str]:
    sets = dict(DEFAULT_SETS)
    for item in items:
        k, v = item.split("=", 1)
        sets[k.strip()] = v.strip()
    return sets


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("upstream", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--set", action="append", default=[])
    args = ap.parse_args()
    text = build(args.upstream.read_text(), parse_sets(args.set))
    v2 = tomllib.loads(args.upstream.read_text())["v2"]["training"]
    got = tomllib.loads(text)["training"]
    diff = {k: (v2.get(k), got.get(k)) for k in set(v2) | set(got) if v2.get(k) != got.get(k)}
    args.out.write_text(text)
    print(f"wrote {args.out}; preset={got['arch_preset']} steps={got.get('training_steps')} diff_vs_v2={diff}")


if __name__ == "__main__":
    main()
