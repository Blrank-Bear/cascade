"""Build a local duel config: upstream chain.toml with [training] replaced by [v2.training].

The loader parses [v2.training] as a complete, standalone contract, so a wholesale
section swap reproduces the lane-A v2 training contract for duel.py / grid.py.
`corpus_mode` defaults to "stream_cpu" (the "shards" mode needs upstream's CPU VM).

    python make_v2_cfg.py UPSTREAM_CHAIN.toml OUT.toml [--set key=value ...]

--set values are written verbatim as TOML (quote strings: --set 'arch_preset="x"').

    python make_v2_cfg.py UPSTREAM_CHAIN.toml OUT.toml --preset 28m [--set ...]

--preset swaps in a smaller official pyramid size (2m/7m/28m) for screening on a
24 GB GPU and re-pins base_arch_digest (run with upstream's venv; cwd = upstream).
"""
from __future__ import annotations

import argparse
import re
import tomllib
from pathlib import Path

DEFAULT_SETS = {"corpus_mode": '"stream_cpu"'}
HEADER = re.compile(r"^\[([^\[\]]+)\]\s*(#.*)?$")


def section_spans(lines: list[str]) -> dict[str, tuple[int, int]]:
    """Map each [table] header to its (start, end) line span (header line included)."""
    heads = [(i, m.group(1).strip()) for i, l in enumerate(lines) if (m := HEADER.match(l.strip()))]
    ends = [i for i, _ in heads[1:]] + [len(lines)]
    return {name: (i, e) for (i, name), e in zip(heads, ends)}


def section_body(lines: list[str], span: tuple[int, int]) -> list[str]:
    return lines[span[0] + 1:span[1]]


def apply_sets(body: list[str], sets: dict[str, str]) -> list[str]:
    """Replace `key = ...` lines in place; append keys that are absent."""
    out, seen = [], set()
    for line in body:
        key = line.split("=", 1)[0].strip() if "=" in line and not line.lstrip().startswith("#") else None
        if key in sets:
            out.append(f"{key} = {sets[key]}\n")
            seen.add(key)
        else:
            out.append(line)
    while out and not out[-1].strip():
        out.pop()
    out += [f"{k} = {v}\n" for k, v in sets.items() if k not in seen]
    return out + ["\n"]


def build(upstream_text: str, sets: dict[str, str]) -> str:
    lines = upstream_text.splitlines(keepends=True)
    spans = section_spans(lines)
    start, end = spans["training"]
    body = apply_sets(section_body(lines, spans["v2.training"]), sets)
    head = ["# Generated by tools/duel/make_v2_cfg.py: [training] := upstream [v2.training].\n"]
    return "".join(head + lines[:start + 1] + body + lines[end:])


# --- [round] size retarget: screen_size / throne_sizes must name the v2 preset ---
ROUND_SIZE_KEYS = ("screen_size", "throne_sizes")


def round_size_line(key: str, preset: str) -> str:
    return f'{key} = ["{preset}"]\n' if key == "throne_sizes" else f'{key} = "{preset}"\n'


def retarget_round_sizes(text: str, preset: str) -> str:
    lines = text.splitlines(keepends=True)
    start, end = section_spans(lines)["round"]
    for i in range(start + 1, end):
        key = lines[i].split("=", 1)[0].strip() if "=" in lines[i] else None
        if key in ROUND_SIZE_KEYS:
            lines[i] = round_size_line(key, preset)
    return "".join(lines)


def build_v2(upstream_text: str, sets: dict[str, str]) -> str:
    text = build(upstream_text, sets)
    return retarget_round_sizes(text, tomllib.loads(text)["training"]["arch_preset"])


# --- screening presets: a smaller official pyramid size (same expert geometry) ---
# Mirrors upstream cascade/trainer/pyramid_model.py CascadeMoEConfig.from_contract.
PRESET_DIMS = {"2m": (128, 276), "7m": (256, 552), "28m": (512, 1104), "120m": (1088, 2346)}


def preset_sets(preset: str) -> dict[str, str]:
    d, ffn = PRESET_DIMS[preset]
    return {"arch_preset": f'"cascade-moe-v2-{preset}"', "d_model": str(d),
            "num_heads": str(d // 64), "d_ff": str(ffn)}


def recompute_digest(out: Path) -> str:
    """Pin base_arch_digest to the arch actually configured (needs upstream's venv)."""
    from cascade.shared.config import load_chain_config
    from cascade.trainer.contract import compute_base_arch_digest
    digest = compute_base_arch_digest(load_chain_config(out).training)
    text = re.sub(r'^base_arch_digest = ".*"$', f'base_arch_digest = "{digest}"',
                  out.read_text(), count=1, flags=re.M)
    out.write_text(text)
    return digest


def main_preset() -> None:
    """Entry for `--preset SIZE`: build the config, then pin the digest for that size."""
    ap = argparse.ArgumentParser()
    ap.add_argument("upstream", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--preset", required=True, choices=sorted(PRESET_DIMS))
    ap.add_argument("--set", action="append", default=[])
    args = ap.parse_args()
    sets = parse_sets(args.set)
    sets.update(preset_sets(args.preset))
    args.out.write_text(build_v2(args.upstream.read_text(), sets))
    digest = recompute_digest(args.out)
    got = tomllib.loads(args.out.read_text())["training"]
    print(f"wrote {args.out}; preset={got['arch_preset']} d_model={got['d_model']} "
          f"micro_batches={got['micro_batches']} digest={digest[:12]}")


def parse_sets(items: list[str]) -> dict[str, str]:
    sets = dict(DEFAULT_SETS)
    for item in items:
        k, v = item.split("=", 1)
        sets[k.strip()] = v.strip()
    return sets


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("upstream", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--set", action="append", default=[])
    args = ap.parse_args()
    text = build_v2(args.upstream.read_text(), parse_sets(args.set))
    v2 = tomllib.loads(args.upstream.read_text())["v2"]["training"]
    got = tomllib.loads(text)["training"]
    diff = {k: (v2.get(k), got.get(k)) for k in set(v2) | set(got) if v2.get(k) != got.get(k)}
    args.out.write_text(text)
    rnd = tomllib.loads(text)["round"]
    print(f"wrote {args.out}; preset={got['arch_preset']} steps={got.get('training_steps')} diff_vs_v2={diff} "
          f"round={[rnd.get(k) for k in ROUND_SIZE_KEYS]}")


if __name__ == "__main__":
    import sys
    main_preset() if "--preset" in sys.argv else main()
